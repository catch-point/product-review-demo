-- schema.sql
-- PostgreSQL (12+) storage for graphs described by context.jsonld.
--

BEGIN;

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

-- An absolute IRI: a scheme followed by ':' (https://example.com/categories/audio).
CREATE DOMAIN iri AS text
  CHECK (VALUE ~ '^[A-Za-z][A-Za-z0-9+.-]*:\S+$');

-- ---------------------------------------------------------------------------
-- Tables (one per context type; columns use the context's term names)
-- ---------------------------------------------------------------------------

-- "Person" (schema:Person): reviewers and owners.
CREATE TABLE person (
  person_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text,
  email          text CHECK (email ~ '^[^@\s]+@[^@\s]+$'),
  "dateCreated"  timestamptz NOT NULL DEFAULT now(),
  "dateModified" timestamptz
);
CREATE UNIQUE INDEX person_email_key ON person (lower(email));

-- Categories are vocabulary terms defined by this site. "term" is the context
-- term that names them ("Audio" -> https://example.com/categories/audio), so
-- graphs can use either form.
CREATE TABLE category (
  id    iri UNIQUE,
  term  text PRIMARY KEY,
  name  text
);

-- "Product" (schema:Product). "owner" doubles as the Person's "owns" (one
-- fact, readable both ways). "discontinuedDate" is internal: it hides a
-- product after its owner deletes it while keeping reviews and replies.
CREATE TABLE product (
  product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              text NOT NULL,
  description       text,
  image             text,
  url               text,
  "sameAs"          INT REFERENCES product (product_id) ON DELETE SET NULL,
  owner             INT REFERENCES person (person_id) ON DELETE SET NULL,
  brand             text,
  gtin              text,
  sku               text,
  mpn               text,
  "dateCreated"     timestamptz NOT NULL DEFAULT now(),
  "dateModified"    timestamptz,
  "discontinuedDate" timestamptz,
  CONSTRAINT product_image_path CHECK (image IS NULL OR image ~ '^/images/[0-9a-f]{64}\.[a-z]+$')
);
CREATE INDEX product_owner_idx ON product (owner);

-- "category" (a set). product_id is part of the primary key, so the link is
-- removed with the product rather than set null.
CREATE TABLE product_category (
  product_id INT NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
  category    iri NOT NULL REFERENCES category (id),
  PRIMARY KEY (product_id, category)
);
CREATE INDEX product_category_category_idx ON product_category (category);


-- "AggregateRating" (schema:AggregateRating) for a Product.
CREATE TABLE aggregate_rating (
  aggregate_rating_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INT NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
  "ratingValue" numeric(3,1) NOT NULL,
  "bestRating"  numeric(3,1) NOT NULL DEFAULT 5,
  "worstRating" numeric(3,1) NOT NULL DEFAULT 1,
  "ratingCount" integer NOT NULL CHECK ("ratingCount" >= 0),
  "reviewCount" integer NOT NULL CHECK ("reviewCount" >= 0),
  "dateCreated" timestamptz NOT NULL DEFAULT now(),
  "dateModified" timestamptz,
  CHECK ("reviewCount" <= "ratingCount"),
  CHECK ("worstRating" < "bestRating"),
  CHECK ("ratingValue" BETWEEN "worstRating" AND "bestRating")
);
CREATE UNIQUE INDEX product_agg_rating_product_key ON aggregate_rating (product_id);

-- "Review" (schema:Review) with its "reviewRating" (schema:Rating) inline.
CREATE TABLE review (
  review_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  "itemReviewed"   INT REFERENCES product (product_id) NOT NULL,
  author           INT REFERENCES person (person_id) NOT NULL,
  "reviewBody"     text,
  image            text,
  "ratingValue"    numeric(3,1) NOT NULL,
  "bestRating"     numeric(3,1) NOT NULL DEFAULT 5,
  "worstRating"    numeric(3,1) NOT NULL DEFAULT 1,
  "datePublished"  timestamptz NOT NULL DEFAULT now(),
  "dateModified"   timestamptz,
  CHECK ("worstRating" < "bestRating"),
  CHECK ("ratingValue" BETWEEN "worstRating" AND "bestRating"),
  CONSTRAINT review_image_path CHECK (image IS NULL OR image ~ '^/images/[0-9a-f]{64}\.[a-z]+$')
);
CREATE INDEX review_item_idx ON review ("itemReviewed", "datePublished" DESC);
CREATE INDEX review_author_idx ON review (author);
CREATE UNIQUE INDEX review_item_author_key ON review ("itemReviewed", author);

-- "Comment" (schema:Comment): replies listed under a Review's "comment".
-- Comments may be blank nodes, so the IRI is optional.
CREATE TABLE comment (
  comment_id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  review_id        bigint NOT NULL REFERENCES review (review_id) ON DELETE CASCADE,
  author           INT REFERENCES person (person_id) NOT NULL,
  text             text NOT NULL,
  "datePublished"  timestamptz NOT NULL DEFAULT now(),
  "dateModified"   timestamptz
);
CREATE UNIQUE INDEX comment_review_author_key ON comment (review_id, author);

-- ---------------------------------------------------------------------------
-- Journal
-- ---------------------------------------------------------------------------
-- Append-only audit of every later insert, update, and delete. old_row is
-- null after INSERT. new_row is null after DELETE. An update stores both.
-- Rows written by one transaction share txid. happened_at is the time of the
-- user statement, so it matches dateModified set by touch_date_modified().
--
-- The application names the actor inside the transaction:
--   BEGIN;
--   SET LOCAL app.actor = 'person:42';
--   SET LOCAL app.skip_journal = 'on';  -- optional, for a migration
-- db_role is session_user, including when journal_write() inserts.

CREATE TABLE journal (
  journal_id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  happened_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  txid        bigint      NOT NULL DEFAULT txid_current(),
  actor       text,
  db_role     text        NOT NULL DEFAULT session_user,
  op          text        NOT NULL CHECK (op IN ('INSERT', 'UPDATE', 'DELETE')),
  table_name  text        NOT NULL,
  pk          jsonb       NOT NULL,
  old_row     jsonb,
  new_row     jsonb,
  CHECK (
    (op = 'INSERT' AND old_row IS NULL AND new_row IS NOT NULL) OR
    (op = 'DELETE' AND old_row IS NOT NULL AND new_row IS NULL) OR
    (op = 'UPDATE' AND old_row IS NOT NULL AND new_row IS NOT NULL)
  )
);
CREATE INDEX journal_table_pk_idx ON journal (table_name, pk, happened_at DESC);
CREATE INDEX journal_happened_at_idx ON journal (happened_at DESC);
CREATE INDEX journal_txid_idx ON journal (txid);

-- Announce every journal entry, so caches can drop what changed.
CREATE FUNCTION journal_refs(j journal) RETURNS jsonb
LANGUAGE sql IMMUTABLE
AS $$
  SELECT jsonb_build_object('table', j.table_name, 'pk', j.pk)
      || jsonb_strip_nulls(jsonb_build_object(
           'product_id', r -> 'product_id',
           'itemReviewed',  r -> 'itemReviewed',
           'review_id',     r -> 'review_id',
           'owner',         r -> 'owner',
           'oldOwner',      j.old_row -> 'owner',
           'email',         r -> 'email'))
  FROM (SELECT coalesce(j.new_row, j.old_row) AS r) AS changed
$$;

-- Delivered to every LISTENing session when the writing transaction commits.
CREATE FUNCTION journal_notify() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  PERFORM pg_notify('journal', journal_refs(NEW)::text);
  RETURN NULL;
END;
$$;

CREATE TRIGGER journal_notify
  AFTER INSERT ON journal
  FOR EACH ROW EXECUTE PROCEDURE journal_notify();

-- Trigger arguments are the primary-key columns, in order.
-- product_category uses journal_write('product_id', 'category').
CREATE FUNCTION journal_write() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  old_row jsonb;
  new_row jsonb;
  row_pk  jsonb := '{}'::jsonb;
  src     jsonb;
  i       integer;
BEGIN
  IF TG_TABLE_NAME IS NULL THEN
    RAISE EXCEPTION 'journal_write() can only be called as a trigger';
  END IF;

  IF current_setting('app.skip_journal', true) = 'on'
     AND pg_has_role(session_user, current_user, 'USAGE') THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'UPDATE' AND OLD IS NOT DISTINCT FROM NEW THEN
    RETURN NULL;
  END IF;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    old_row := to_jsonb(OLD);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    new_row := to_jsonb(NEW);
  END IF;

  src := coalesce(new_row, old_row);
  IF TG_NARGS = 0 THEN
    RAISE EXCEPTION 'journal_write requires primary-key column names';
  END IF;

  FOR i IN 0 .. TG_NARGS - 1 LOOP
    IF (NOT (src ? TG_ARGV[i])) OR src -> TG_ARGV[i] = 'null'::jsonb THEN
      RAISE EXCEPTION 'journal_write: %.% has no primary-key value in %',
        TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_ARGV[i];
    END IF;
    row_pk := row_pk || jsonb_build_object(TG_ARGV[i], src -> TG_ARGV[i]);
  END LOOP;

  EXECUTE format(
    'INSERT INTO %I.journal (op, table_name, pk, old_row, new_row, actor)
     VALUES ($1, $2, $3, $4, $5, $6)',
    TG_TABLE_SCHEMA
  ) USING TG_OP, TG_TABLE_NAME, row_pk, old_row, new_row,
           nullif(current_setting('app.actor', true), '');

  RETURN NULL;
END;
$$;

CREATE FUNCTION journal_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  RAISE EXCEPTION 'journal is append-only';
END;
$$;

-- A real column change stamps dateModified. A no-op update leaves the row
-- unchanged, so the journal trigger records nothing. A write that changes
-- only dateModified keeps the submitted value.
CREATE FUNCTION touch_date_modified() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD
     AND (OLD."dateModified" IS NOT DISTINCT FROM NEW."dateModified") THEN
    NEW."dateModified" = now();
  END IF;
  RETURN NEW;
END;
$$;

