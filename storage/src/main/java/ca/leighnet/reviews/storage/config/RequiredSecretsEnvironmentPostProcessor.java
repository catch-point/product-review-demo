package ca.leighnet.reviews.storage.config;

import java.util.ArrayList;
import java.util.List;

import org.springframework.boot.EnvironmentPostProcessor;
import org.springframework.boot.SpringApplication;
import org.springframework.boot.WebApplicationType;
import org.springframework.core.Ordered;
import org.springframework.core.env.ConfigurableEnvironment;
import org.springframework.util.PlaceholderResolutionException;

/**
 * Refuses to start when a password the service needs has not been provided.
 * application.yml's password placeholders have no default values: binding
 * leaves an unset one as its literal {@code ${...}} text, which would reach
 * the database as a password and fail there with a confusing authentication
 * error, and reading the property raises {@link PlaceholderResolutionException}.
 * Each missing password is named here instead, before anything connects:
 * they are in the repository root's {@code .env}, generated by
 * {@code scripts/secrets.sh} (exported, or through launch.json's envFile;
 * Docker's compose files supply their own and refuse to start without them).
 *
 * <p>
 * {@code reviews.require-secrets=false} turns the check off where the
 * credentials are supplied otherwise, with no {@code .env}: the tests, whose
 * {@code src/test/resources/application.properties} says so
 * (TestcontainersConfiguration's credentials, or {@code @SpringBootTest}
 * properties).
 */
public class RequiredSecretsEnvironmentPostProcessor implements EnvironmentPostProcessor, Ordered {

	@Override
	public int getOrder() {
		// After ConfigDataEnvironmentPostProcessor, so application.yml has
		// been loaded and its placeholders resolved (or left alone).
		return Ordered.LOWEST_PRECEDENCE;
	}

	@Override
	public void postProcessEnvironment(ConfigurableEnvironment environment, SpringApplication application) {
		if (!environment.getProperty("reviews.require-secrets", Boolean.class, true)) {
			return;
		}
		List<String> missing = new ArrayList<>();
		require(environment, "spring.datasource.password", "STORAGE_DB_SERVICE_PASSWORD", missing);
		if (environment.getProperty("spring.flyway.enabled", Boolean.class, true)) {
			require(environment, "spring.flyway.password", "STORAGE_DB_OWNER_PASSWORD", missing);
		}
		// The actuator is served by the web application alone (not by Migrate).
		if (application.getWebApplicationType() != WebApplicationType.NONE) {
			require(environment, "reviews.actuator.password", "ACTUATOR_PASSWORD", missing);
		}
		if (environment.getProperty("spring.boot.admin.client.enabled", Boolean.class, false)) {
			require(environment, "spring.boot.admin.client.password", "ADMIN_PASSWORD", missing);
		}
		if (!missing.isEmpty()) {
			throw new IllegalStateException(String.join("\n", missing)
					+ "\nRun scripts/secrets.sh at the repository root and export its .env (set -a; . ./.env),"
					+ " or use a VS Code launch configuration, which reads .env; in Docker the compose files"
					+ " provide these passwords themselves.");
		}
	}

	private static void require(ConfigurableEnvironment environment, String property, String key,
			List<String> missing) {
		String value;
		try {
			value = environment.getProperty(property);
		}
		catch (PlaceholderResolutionException ex) {
			value = null;
		}
		if (value == null || value.isBlank() || value.startsWith("${")) {
			missing.add(property + " could not be read: " + key + " is not set.");
		}
	}

}
