#!/usr/bin/env bash
# Populates the storage service from a seed data file: people, products,
# their reviewers, reviews and comment threads, all through the REST API.
#
#   scripts/seed-products.sh [data.json]
#
# Data defaults to scripts/seed/catalog.json:
#
#   { people: [ { key, name, email } ],
#     products: [ { owner, name, description, category, brand, gtin, sku, mpn,
#                   url, photo?, reviews?: [ { author, body, rating,
#                   photo?, comments?: [ { by: "owner", text } ] } ] } ] }
#
# Each product's "owner" is a person key in people; it becomes the product's
# owner and the only one who replies to its reviews. "photo" and "reviews"
# are optional. Owners act with the owner role, everyone else as reviewers.
#
# Environment:
#   BASE        service URL (default http://localhost:8080)
#   JWT_SECRET  must match the service's reviews.security.jwt-secret, and the
#               service must accept development tokens: DEV_TOKENS=true in
#               .env (or the environment) when it starts
# Needs curl, jq and python3 (to draw the placeholder photos).
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
data=${1:-$here/seed/catalog.json}
BASE=${BASE:-http://localhost:8080}
if [[ -z ${JWT_SECRET:-} && -f $here/../../.env ]]; then
  set -a
  # shellcheck source=/dev/null # Generated by scripts/secrets.sh, not in the repository.
  source "$here/../../.env"
  set +a
fi
export JWT_SECRET=${JWT_SECRET:?JWT_SECRET is not set: run scripts/secrets.sh at the repository root}

for tool in curl jq python3; do
  command -v "$tool" >/dev/null || { echo "seed: $tool is required" >&2; exit 1; }
done
[[ -r $data ]] || { echo "seed: cannot read $data" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# --- helpers ---------------------------------------------------------------

# api METHOD URL EMAIL [curl args...]: prints the response body; fails on
# any status other than 2xx (or the statuses listed in $ALLOW). Past the
# storage service's rate limit (429), waits as long as it says and retries.
api() {
  local method=$1 url=$2 email=$3
  shift 3
  [[ $url == http* ]] || url=$BASE$url
  local status wait
  while :; do
    status=$(curl -sS -o "$work/body" -D "$work/headers" -w '%{http_code}' -X "$method" "$url" \
      -H "Authorization: Bearer $(ROLE=$(role_of "$email") "$here/dev-token.sh" "$email")" "$@")
    [[ $status == 429 ]] || break
    wait=$(tr -d '\r' <"$work/headers" | awk -F': *' 'tolower($1) == "retry-after" { print $2 }')
    echo "  (rate limited; waiting ${wait:-5}s)" >&2
    sleep "${wait:-5}"
  done
  if [[ $status != 2* && " ${ALLOW:-} " != *" $status "* ]]; then
    echo "seed: $method $url as $email failed with $status:" >&2
    cat "$work/body" >&2
    echo >&2
    exit 1
  fi
  cat "$work/body"
}

post_json() { api POST "$1" "$2" -H 'Content-Type: application/ld+json' --data-binary "$3"; }

# role_of EMAIL: owner if they own any product in the data, else reviewer.
role_of() {
  if grep -qxF "$1" "$work/owners"; then echo owner; else echo reviewer; fi
}

email_of() {
  jq -r --arg key "$1" '.people[] | select(.key == $key) | .email' "$data" | head -1
}

# normalize: prints one compact JSON object per product with
# { owner: <key>, product: <object>, photo: <object|null>, reviews: [...] }.
normalize() {
  jq -c '
    (.products // [])[]
    | { owner: .owner,
        product: (del(.owner, .photo, .reviews) + {type: "Product"}),
        photo: (.photo // null),
        reviews: (.reviews // []) }
  ' "$data"
}

# photo FROM TO: draws a 640x480 gradient PNG and prints its path.
photo() {
  local file
  file=$(mktemp "$work/photo-XXXXXX.png")
  python3 - "$1" "$2" "$file" <<'PY'
import struct, sys, zlib
start, end, path = sys.argv[1], sys.argv[2], sys.argv[3]
rgb = lambda c: [int(c.lstrip('#')[i:i + 2], 16) for i in (0, 2, 4)]
a, b = rgb(start), rgb(end)
w, h = 640, 480
rows = bytearray()
for y in range(h):
    rows.append(0)
    for x in range(w):
        t = (x / w + y / h) / 2
        rows.extend(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
def chunk(kind, body):
    return struct.pack('>I', len(body)) + kind + body + struct.pack('>I', zlib.crc32(kind + body))
png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
png += chunk(b'IDAT', zlib.compress(bytes(rows), 9)) + chunk(b'IEND', b'')
open(path, 'wb').write(png)
PY
  echo "$file"
}

# upload EMAIL FROM TO: uploads a generated photo and prints its URL.
upload() {
  api POST /images "$1" -F "file=@$(photo "$2" "$3");type=image/png" | jq -r .id
}

# The service refuses development tokens (401) unless it was started with
# them on: say so, rather than fail on the first write.
status=$(curl -sS -o /dev/null -w '%{http_code}' "$BASE/people/me" \
  -H "Authorization: Bearer $(ROLE=reviewer "$here/dev-token.sh" seed-check@example.com)")
if [[ $status == 401 ]]; then
  echo "seed: $BASE does not accept development tokens. Set DEV_TOKENS=true in .env, then" \
    "scripts/stack.sh storage up (or restart the service you run)." >&2
  exit 1
fi

curl -sSf "$BASE/readyz" >/dev/null \
  || { echo "seed: the service is not ready at $BASE" >&2; exit 1; }

jq -r '(.people // []) as $people
    | [.products[]? | .owner]
    | unique[] as $key
    | $people[] | select(.key == $key) | .email' "$data" >"$work/owners"

# The names already there, so seeding twice fails before creating duplicates.
url="$BASE/products?limit=100"
while [[ -n $url ]]; do
  page=$(curl -sS "$url")
  jq -r '.member[] | "\(.name)\t\(.id)"' <<<"$page" >>"$work/existing"
  url=$(jq -r '.view.next // empty' <<<"$page")
done

# --- people ----------------------------------------------------------------

echo "Registering people"
while read -r person; do
  email=$(jq -r .email <<<"$person")
  ALLOW=409 post_json /people "$email" "$(jq -c '{type: "Person", name}' <<<"$person")" >/dev/null
  echo "  $(jq -r .name <<<"$person") <$email>"
done < <(jq -c '.people[]?' "$data")

# --- products, reviews and comments -------------------------------------

created=()
seed_product() {
  local entry=$1
  local owner_key name owner_email image
  owner_key=$(jq -r .owner <<<"$entry")
  [[ -n $owner_key && $owner_key != null ]] \
    || { echo "seed: a product has no owner key" >&2; exit 1; }
  owner_email=$(email_of "$owner_key")
  [[ -n $owner_email ]] || { echo "seed: owner '$owner_key' is not in people" >&2; exit 1; }

  name=$(jq -r .product.name <<<"$entry")

  local existing
  existing=$(awk -F '\t' -v name="$name" '$1 == name { print $2; exit }' "$work/existing")
  if [[ -n $existing ]]; then
    echo "seed: $name already exists at $existing; delete it (as its owner) to seed again." >&2
    exit 1
  fi

  echo "Creating $name"
  image=""
  if [[ $(jq -r '.photo != null' <<<"$entry") == true ]]; then
    image=$(upload "$owner_email" "$(jq -r .photo.from <<<"$entry")" "$(jq -r .photo.to <<<"$entry")")
  fi
  local body
  body=$(jq -c --arg image "$image" \
    '.product + (if $image == "" then {} else {image: $image} end)' <<<"$entry")
  local product
  product=$(post_json /products "$owner_email" "$body" | jq -r .id)
  echo "  $product"
  created+=("$product")

  echo "  Adding reviews"
  while read -r review; do
    local author author_email
    author=$(jq -r .author <<<"$review")
    author_email=$(email_of "$author")
    [[ -n $author_email ]] || { echo "seed: author '$author' is not in people" >&2; exit 1; }

    local rimage=""
    if jq -e .photo >/dev/null <<<"$review"; then
      rimage=$(upload "$author_email" "$(jq -r .photo.from <<<"$review")" "$(jq -r .photo.to <<<"$review")")
    fi
    local rbody
    rbody=$(jq -c --arg image "$rimage" '{
        type: "Review",
        reviewBody: .body,
        reviewRating: {type: "Rating", ratingValue: .rating, bestRating: 5, worstRating: 1}
      } + (if $image == "" then {} else {image: $image} end)' <<<"$review")
    local id
    id=$(post_json "$product/reviews" "$author_email" "$rbody" | jq -r .id)
    echo "    $(jq -r .rating <<<"$review")/5 by $author${rimage:+ (with photo)}: $id"

    while read -r comment; do
      if [[ $(jq -r .by <<<"$comment") != owner ]]; then
        echo "      skipped a reply not by the owner" >&2
        continue
      fi
      post_json "$id/comments" "$owner_email" "$(jq -c '{type: "Comment", text}' <<<"$comment")" >/dev/null
      echo "      reply by $owner_email"
    done < <(jq -c '.comments // [] | .[]' <<<"$review")
  done < <(jq -c '.reviews[]?' <<<"$entry")
}

while read -r entry; do
  seed_product "$entry"
done < <(normalize)

# --- summary ---------------------------------------------------------------

echo
for product in "${created[@]}"; do
  [[ $product == http* ]] || product=$BASE$product
  curl -sS "$product" \
    | jq -r '"Done: \(.name) has \(.aggregateRating.ratingCount) reviews averaging \(.aggregateRating.ratingValue)/5 at \(.id)"'
done
