  FOR EACH ROW EXECUTE PROCEDURE journal_write('comment_id');
CREATE TRIGGER comment_touch_date_modified
  BEFORE UPDATE ON comment
  FOR EACH ROW EXECUTE PROCEDURE touch_date_modified();

CREATE TRIGGER journal_guard
  BEFORE INSERT OR UPDATE OR DELETE ON journal
  FOR EACH ROW EXECUTE PROCEDURE journal_guard();

COMMIT;
