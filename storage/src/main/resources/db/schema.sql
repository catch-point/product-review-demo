-- Triggers: audit every table that represents a resource or a relation
-- the API exposes (product_category carries a product's categories). The
-- journal's own changes are blocked (journal_guard). Journal triggers run
-- AFTER so they see values set by touch_date_modified() and by defaults.

CREATE TRIGGER person_audit
  AFTER INSERT OR UPDATE OR DELETE ON person
  FOR EACH ROW EXECUTE PROCEDURE journal_write('person_id');
CREATE TRIGGER person_touch_date_modified
  BEFORE UPDATE ON person
  FOR EACH ROW EXECUTE PROCEDURE touch_date_modified();

CREATE TRIGGER category_audit
  AFTER INSERT OR UPDATE OR DELETE ON category
  FOR EACH ROW EXECUTE PROCEDURE journal_write('term');
CREATE TRIGGER category_touch_date_modified
  BEFORE UPDATE ON category
  FOR EACH ROW EXECUTE PROCEDURE touch_date_modified();

CREATE TRIGGER product_audit
  AFTER INSERT OR UPDATE OR DELETE ON product
  FOR EACH ROW EXECUTE PROCEDURE journal_write('product_id');
CREATE TRIGGER product_touch_date_modified
  BEFORE UPDATE ON product
  FOR EACH ROW EXECUTE PROCEDURE touch_date_modified();

CREATE TRIGGER product_category_audit
  AFTER INSERT OR UPDATE OR DELETE ON product_category
  FOR EACH ROW EXECUTE PROCEDURE journal_write('product_id', 'category');
CREATE TRIGGER aggregate_rating_audit
  AFTER INSERT OR UPDATE OR DELETE ON aggregate_rating
  FOR EACH ROW EXECUTE PROCEDURE journal_write('aggregate_rating_id');
CREATE TRIGGER aggregate_rating_touch_date_modified
  BEFORE UPDATE ON aggregate_rating
  FOR EACH ROW EXECUTE PROCEDURE touch_date_modified();

CREATE TRIGGER review_audit
  AFTER INSERT OR UPDATE OR DELETE ON review
  FOR EACH ROW EXECUTE PROCEDURE journal_write('review_id');
